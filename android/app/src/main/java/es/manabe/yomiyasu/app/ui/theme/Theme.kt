@Composable
fun YomiyasuTheme(
    themeMode: ThemeMode = ThemeMode.System,
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themeMode) {
        ThemeMode.System -> isSystemInDarkTheme()
        ThemeMode.Light -> false
        ThemeMode.Dark -> true
    }
    val colorScheme = if (darkTheme) DarkScheme else LightScheme
    val accentColors = YomiyasuAccentColors(
        accent = if (darkTheme) DarkAccent else LightAccent,
        difficulty = DifficultyColors,
        star = StarColor,
    )

    val view = LocalView.current
    if (!view.isInEditMode) {
        val context = LocalContext.current
        SideEffect {
            val window = (context as? Activity)?.window ?: return@SideEffect
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
            WindowCompat.getInsetsController(window, view).isAppearanceLightNavigationBars = !darkTheme
        }
    }

    CompositionLocalProvider(LocalYomiyasuColors provides accentColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = YomiyasuTypography,
            content = content,
        )
    }
}
